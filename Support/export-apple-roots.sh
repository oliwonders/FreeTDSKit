#!/bin/bash
# Write Sources/FreeTDSKit/AppleRootCertificates.pem: the root certificates of
# Apple's trust store, as shipped in this Mac's
# /System/Library/Keychains/SystemRootCertificates.keychain, one PEM block each
# with its subject and SHA-256 fingerprint above it.
#
# Why: OpenSSL can't read Apple's trust store. On macOS FreeTDSKit exports the
# live store at runtime (SecTrustCopyAnchorCertificates), but iOS has no API
# that lists the trusted roots, so on iOS and iPadOS FreeTDSKit verifies server
# certificates against this snapshot instead. iOS and macOS share one root
# program, so the snapshot is the same set of roots, frozen at the time this
# script last ran. buildandlinkfreetds.sh runs it, so every framework rebuild
# refreshes it; review the diff before committing.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUTPUT="$SCRIPT_DIR/../Sources/FreeTDSKit/AppleRootCertificates.pem"
KEYCHAIN="/System/Library/Keychains/SystemRootCertificates.keychain"

work="$(mktemp -d "${TMPDIR:-/tmp}/apple-roots.XXXXXX")"
trap 'rm -rf "$work"' EXIT

security find-certificate -a -p "$KEYCHAIN" > "$work/all.pem"
# One file per certificate.
awk -v dir="$work" '
    /-----BEGIN CERTIFICATE-----/ { n++; file = sprintf("%s/cert-%04d.pem", dir, n) }
    file != "" { print > file }
    /-----END CERTIFICATE-----/ { close(file); file = "" }
' "$work/all.pem"

# Sorted by fingerprint, so the file only changes when the set of roots does.
for cert in "$work"/cert-*.pem; do
    fingerprint="$(/usr/bin/openssl x509 -in "$cert" -noout -fingerprint -sha256 | sed 's/^.*=//')"
    subject="$(/usr/bin/openssl x509 -in "$cert" -noout -subject | sed 's/^subject= *//')"
    {
        echo "# $subject"
        echo "# SHA-256 $fingerprint"
        cat "$cert"
        echo ""
    } > "$work/entry-$fingerprint"
done

count="$(ls "$work"/entry-* | wc -l | tr -d ' ')"
if [ "$count" -lt 50 ]; then
    echo "❌ Only $count root certificates in $KEYCHAIN; refusing to write a partial trust store"
    exit 1
fi

{
    echo "# Apple root certificates for FreeTDSKit on iOS and iPadOS."
    echo "# Generated by Support/export-apple-roots.sh from $KEYCHAIN"
    echo "# on macOS $(sw_vers -productVersion) ($(sw_vers -buildVersion)): $count certificates."
    echo "# Do not edit by hand."
    echo ""
    cat $(ls "$work"/entry-* | sort)
} > "$OUTPUT"

echo "✅ $count Apple root certificates -> Sources/FreeTDSKit/AppleRootCertificates.pem"
